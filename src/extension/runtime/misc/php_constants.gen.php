<?php
// Generates php_constants.rs: the global constants of PHP 8.5.13 that the oracle defines in the extensions whose
// behaviour twig-rs reproduces (Core, standard, pcre, json, mbstring, iconv, random), with the oracle's values and
// the deprecation suffixes of `#[\Deprecated]` constants. `ext/date` constants come from twig-date; resources
// (STDIN, STDOUT, STDERR) are not modelled.
//
// Regenerate from the repository root (Git Bash on Windows needs MSYS_NO_PATHCONV=1):
//
//     docker run --rm -i twig-oracle:3.31.1 php < src/extension/runtime/misc/php_constants.gen.php \
//         > src/extension/runtime/misc/php_constants.rs

const EXTENSIONS = ['Core', 'standard', 'pcre', 'json', 'mbstring', 'iconv', 'random'];

function rust_bytes(string $s): string
{
    $out = 'b"';
    for ($i = 0; $i < strlen($s); ++$i) {
        $c = $s[$i];
        $o = ord($c);
        if ('"' === $c || '\\' === $c) {
            $out .= '\\'.$c;
        } elseif ($o >= 0x20 && $o < 0x7F) {
            $out .= $c;
        } elseif ("\n" === $c) {
            $out .= '\\n';
        } elseif ("\r" === $c) {
            $out .= '\\r';
        } elseif ("\t" === $c) {
            $out .= '\\t';
        } else {
            $out .= sprintf('\\x%02x', $o);
        }
    }

    return $out.'"';
}

function rust_value(mixed $v): string
{
    return match (true) {
        null === $v => 'C::Null',
        is_bool($v) => 'C::Bool('.($v ? 'true' : 'false').')',
        is_int($v) => \PHP_INT_MIN === $v ? 'C::Int(i64::MIN)' : 'C::Int('.$v.')',
        is_float($v) => 'C::Float(0x'.bin2hex(pack('E', $v)).')',
        is_string($v) => 'C::Str('.rust_bytes($v).')',
    };
}

$all = get_defined_constants(true);
$constants = [];
foreach (EXTENSIONS as $extension) {
    foreach ($all[$extension] as $name => $value) {
        if (is_resource($value)) {
            continue;
        }
        $constants[$name] = $value;
    }
}
ksort($constants, \SORT_STRING);

$deprecation = null;
set_error_handler(static function (int $type, string $message) use (&$deprecation): bool {
    $deprecation = $message;

    return true;
});

$rows = [];
foreach ($constants as $name => $value) {
    $suffix = 'None';
    if ((new ReflectionConstant($name))->isDeprecated()) {
        $deprecation = null;
        constant($name);
        $prefix = "Constant $name is deprecated";
        if (null === $deprecation || !str_starts_with($deprecation, $prefix)) {
            fwrite(\STDERR, "unexpected deprecation for $name: ".var_export($deprecation, true)."\n");
            exit(1);
        }
        $suffix = 'Some('.rust_bytes(substr($deprecation, strlen($prefix))).')';
    }
    $rows[] = sprintf("    PhpConstant {\n        name: \"%s\",\n        value: %s,\n        deprecated: %s,\n    },\n", $name, rust_value($value), $suffix);
}
restore_error_handler();

echo '//! The global constants of PHP ', \PHP_VERSION, ' defined by the extensions ', implode(', ', EXTENSIONS), ",\n";
echo "//! as the oracle defines them (generated by `php_constants.gen.php`; do not edit).\n\n";
echo "/// The value of a [`PhpConstant`] (floats as IEEE-754 bits).\n";
echo "#[derive(Clone, Copy, Debug)]\n";
echo "pub(super) enum C {\n    Null,\n    Bool(bool),\n    Int(i64),\n    Float(u64),\n    Str(&'static [u8]),\n}\n\n";
echo "/// A global constant: its name, its value and the text PHP appends to `Constant %s is deprecated` when it is\n";
echo "/// deprecated.\n";
echo "#[derive(Clone, Copy, Debug)]\n";
echo "pub(super) struct PhpConstant {\n    pub(super) name: &'static str,\n    pub(super) value: C,\n    pub(super) deprecated: Option<&'static [u8]>,\n}\n\n";
echo "/// The constants, sorted by name (byte order).\n";
echo "pub(super) static CONSTANTS: &[PhpConstant] = &[\n";
echo implode('', $rows);
echo "];\n";
