#!/bin/sh
# Generates html_entities.rs from php-src 8.5.13's ext/standard/html_tables.h:
#
#   cd crates/twig-value/src/builtins/string
#   sh html_entities.gen.sh /path/to/php-src-8.5.13 > html_entities.rs
set -e
tables="$1/ext/standard/html_tables.h"
names() {
    grep "^static const entity_cp_map ht_bucket_$1_" "$tables" | grep -o '{"[A-Za-z0-9]*", [0-9]*' \
        | sed 's/{"\([A-Za-z0-9]*\)".*/\1/' | LC_ALL=C sort -u
}
html4=$(names html4)
html5=$(names html5)
echo '//! Named character references recognised by `htmlspecialchars(..., double_encode: false)`:'
echo '//! the entity names of the `ent_ht_html4` and `ent_ht_html5` tables of'
echo '//! PHPSRC/ext/standard/html_tables.h, sorted bytewise for binary search. Generated by'
echo '//! `html_entities.gen.sh` (next to this file); do not edit by hand.'
echo
echo '/// HTML 4.01 entity names (`ent_ht_html4`, used for `ENT_HTML401` and `ENT_XHTML`).'
echo "pub(super) static HTML4: [&str; $(echo "$html4" | wc -l)] = ["
echo "$html4" | sed 's/.*/    "&",/'
echo '];'
echo
echo '/// HTML 5 entity names (`ent_ht_html5`, used for `ENT_HTML5`).'
echo "pub(super) static HTML5: [&str; $(echo "$html5" | wc -l)] = ["
echo "$html5" | sed 's/.*/    "&",/'
echo '];'
