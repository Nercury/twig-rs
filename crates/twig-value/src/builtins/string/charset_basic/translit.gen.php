<?php
// Generates translit_table.rs: what //TRANSLIT turns a character into when the target charset cannot represent it.
//
// Black-box only: every code point is converted with PHP's iconv() in the oracle (glibc 2.41, LC_CTYPE=C.UTF-8,
// the locale PHP runs with there), one character between \x01 separators per slot of a batch, for the three targets
// whose repertoire is smaller than Unicode: ANSI_X3.4-1968 (U+0080 and up), ISO-8859-1 (U+0100 and up) and UCS-2
// (U+10000 and up). Characters that come out as "?" (glibc's replacement when it knows no transliteration) are left
// out. Pairs of characters were checked to transliterate like the two characters on their own (no multi-character
// rules in this locale); the tests in tests/charset_basic.rs compare the table with oracle vectors.
//
// Regenerate (from crates/twig-value/src/builtins/string/charset_basic, Git Bash):
//   MSYS_NO_PATHCONV=1 docker run --rm -v "$(pwd -W 2>/dev/null || pwd):/t" twig-oracle:3.31.1 \
//       php /t/translit.gen.php > translit_table.rs

declare(strict_types=1);
ini_set('memory_limit', '-1');

if (setlocale(LC_CTYPE, '0') !== 'C.UTF-8') {
    fwrite(STDERR, "expected LC_CTYPE=C.UTF-8\n");
    exit(1);
}

/** @return array<int, list<int>> code point => replacement code points, for every result other than "?" */
function table(string $target, int $lo, int $hi, int $unit): array
{
    $out = [];
    $sep = $unit === 2 ? "\x01\x00" : "\x01";
    for ($start = $lo; $start <= $hi; $start += 4096) {
        $cps = [];
        $in = '';
        for ($cp = $start; $cp < $start + 4096 && $cp <= $hi; $cp++) {
            if ($cp >= 0xD800 && $cp <= 0xDFFF) {
                continue;
            }
            $cps[] = $cp;
            $in .= mb_chr($cp, 'UTF-8') . "\x01";
        }
        $converted = iconv('UTF-8', "$target//TRANSLIT", $in);
        if ($converted === false) {
            throw new RuntimeException("batch $target $start failed");
        }
        $parts = [];
        $cur = [];
        for ($i = 0; $i < strlen($converted); $i += $unit) {
            $u = substr($converted, $i, $unit);
            if ($u === $sep) {
                $parts[] = $cur;
                $cur = [];
            } else {
                $cur[] = $unit === 2 ? unpack('v', $u)[1] : ord($u);
            }
        }
        if (count($parts) !== count($cps)) {
            throw new RuntimeException("batch $target $start: " . count($parts) . ' results for ' . count($cps));
        }
        foreach ($cps as $k => $cp) {
            if ($parts[$k] !== [0x3F]) {
                $out[$cp] = $parts[$k];
            }
        }
    }
    return $out;
}

$ascii = table('ANSI_X3.4-1968', 0x80, 0x10FFFF, 1);
$latin1 = table('ISO-8859-1', 0x100, 0x10FFFF, 1);
$ucs2 = table('UCS-2LE', 0x10000, 0x10FFFF, 2);

// ISO-8859-1 differs from ASCII in a few dozen entries (alternatives that use Latin-1 characters)
$latin1Overrides = [];
for ($cp = 0x100; $cp <= 0x10FFFF; $cp++) {
    $a = $ascii[$cp] ?? [0x3F];
    $l = $latin1[$cp] ?? [0x3F];
    if ($a !== $l) {
        $latin1Overrides[$cp] = $l;
    }
}

/** Emits KEYS (sorted code points), SPANS (offset, length) into DATA. */
function emit(string $name, string $doc, array $table, string $unitType): void
{
    ksort($table);
    $data = [];
    $spans = [];
    $index = [];
    foreach ($table as $cp => $rep) {
        $k = implode(',', $rep);
        if (!isset($index[$k])) {
            // reuse an identical earlier replacement
            $index[$k] = count($data);
            array_push($data, ...$rep);
        }
        $spans[] = sprintf('(%d, %d)', $index[$k], count($rep));
    }
    $n = count($table);
    echo "/// $doc\n";
    printf("pub(super) static %s_KEYS: [u32; %d] = [\n", $name, $n);
    foreach (array_chunk(array_keys($table), 12) as $chunk) {
        echo '    ', implode(', ', array_map(static fn (int $c): string => sprintf('0x%04X', $c), $chunk)), ",\n";
    }
    echo "];\n\n";
    printf("/// `(offset, length)` of the replacement of each `%s_KEYS` entry in `%s_DATA`.\n", $name, $name);
    printf("pub(super) static %s_SPANS: [(u16, u8); %d] = [\n", $name, $n);
    foreach (array_chunk($spans, 10) as $chunk) {
        echo '    ', implode(', ', $chunk), ",\n";
    }
    echo "];\n\n";
    printf("/// The replacements of `%s_KEYS`, concatenated.\n", $name);
    printf("pub(super) static %s_DATA: [%s; %d] = [\n", $name, $unitType, count($data));
    foreach (array_chunk($data, 16) as $chunk) {
        echo '    ', implode(', ', array_map(static fn (int $c): string => $unitType === 'u8' ? sprintf('0x%02X', $c) : sprintf('0x%04X', $c), $chunk)), ",\n";
    }
    echo "];\n\n";
}

echo "//! Generated by translit.gen.php (black-box: PHP iconv() with //TRANSLIT in the oracle); do not edit.\n";
echo "//!\n";
echo "//! glibc 2.41 transliteration under LC_CTYPE=C.UTF-8 for the targets with a smaller repertoire than Unicode.\n";
echo "//! Characters that are not listed become \"?\".\n\n";
emit('ASCII', 'Code points from U+0080 up whose ANSI_X3.4-1968 transliteration is not "?".', $ascii, 'u8');
emit('LATIN1', 'Code points from U+0100 up whose ISO-8859-1 transliteration differs from the ASCII one (`ASCII_*`).', $latin1Overrides, 'u8');
emit('UCS2', 'Code points from U+10000 up whose UCS-2 transliteration is not "?".', $ucs2, 'u16');
