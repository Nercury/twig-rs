//! Unicode 17.0 tables and PHP mbstring-compatible text functions for UTF-8 byte strings.
//!
//! Strings are byte slices, as in PHP: input need not be valid UTF-8, and the functions treat
//! ill-formed sequences exactly as PHP 8.5.13's mbstring does (see [`utf8`]). Results match
//! PHP byte for byte, which the oracle vectors in `tests/vectors/` check.
//!
//! - [`mbstring`]: `mb_strlen`, `mb_substr`, `mb_str_split`, `mb_strtoupper`, `mb_strtolower`,
//!   `mb_convert_case`, `mb_ucfirst`, `mb_lcfirst`, `mb_check_encoding` and `mb_ord` for UTF-8
//!   (re-exported at the crate root).
//! - [`case`]: case mapping of strings ([`convert_case`] with a [`CaseMode`]) and of single code
//!   points, ported from `PHPSRC/ext/mbstring/php_unicode.c`.
//! - [`props`]: the character properties of mbstring's tables, including `Cased` and
//!   `Case_Ignorable`.
//! - [`utf8`]: mbstring-compatible UTF-8 decoding into code points and markers for ill-formed
//!   sequences, and encoding with `?` substitution.
//!
//! Only UTF-8 is supported; other mbstring encodings are not implemented.
//!
//! # Licences
//!
//! The tables in `src/tables.rs` are converted from php-src's `ext/mbstring/unicode_data.h`
//! (generated by php-src from the Unicode Character Database: Unicode License v3, and PHP
//! License 3.01 for php-src). The case-mapping and property code ports
//! `ext/mbstring/php_unicode.c` and the mbstring functions port `ext/mbstring/mbstring.c`
//! (PHP License 3.01; `php_unicode.c` is based on ucdata-2.5, Copyright 2001 Computing
//! Research Labs, New Mexico State University). The UTF-8 decoder follows the Unicode standard
//! and was checked against PHP's behaviour; no code from libmbfl (LGPL) is used.

#![warn(missing_docs)]

#[rustfmt::skip]
mod tables;

pub mod case;
pub mod mbstring;
pub mod props;
pub mod utf8;

pub use case::{CaseMode, convert_case};
pub use mbstring::{
    ValueError, mb_check_encoding, mb_convert_case, mb_lcfirst, mb_ord, mb_str_split, mb_strlen,
    mb_strtolower, mb_strtoupper, mb_substr, mb_ucfirst,
};

/// Version of the Unicode Character Database behind the tables (that of PHP 8.5.13's mbstring).
pub const UNICODE_VERSION: (u8, u8, u8) = (17, 0, 0);
