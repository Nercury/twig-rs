#!/usr/bin/env python3
"""Assembles src/parse_iso_intervals/scanner.re, the re2rust input for the timelib_strtointerval() scanner.

Usage: python -I tools/gen_iso_scanner_re.py <PHPSRC>/ext/date/lib/parse_iso_intervals.re \
           src/parse_iso_intervals/scanner.re

Same layout as tools/gen_scanner_re.py (which does this for parse_date.re):
  * a Rust prelude (imports, the TIMELIB_INIT macro, the scan() function head),
  * the regular-expression definitions block of timelib's parse_iso_intervals.re, copied VERBATIM (the first
    `/*!re2c ... */` block inside scan()),
  * tools/iso_scanner_rules.re.rs: the rules block, whose patterns and order are verbatim from
    parse_iso_intervals.re and whose C actions are translated to Rust one to one,
  * the function tail and `/*!max:re2c */` (YYMAXFILL).

Then run tools/regen_scanner.sh to turn scanner.re into scanner.rs with re2rust 4.1.
"""
import os
import sys

HEADER = r'''//! The `timelib_strtointerval()` scanner (port of `scan()` in `PHPSRC/ext/date/lib/parse_iso_intervals.re`).
//!
//! GENERATED by re2rust 4.1 from `scanner.re` (see `tools/gen_iso_scanner_re.py` and `tools/regen_scanner.sh`);
//! do not edit by hand. The regular-expression definitions and rules are verbatim from timelib 2022.17; the
//! actions are line-by-line Rust translations of the C actions, calling the helpers in
//! `parse_iso_intervals/mod.rs`.

use super::*;

/// `TIMELIB_INIT`: remember where the token ends and take a NUL-terminated copy of it.
macro_rules! init {
    ($s:ident, $cursor:ident, $str:ident, $ptr:ident) => {
        $s.cur = $cursor;
        let $str = $s.token();
        #[allow(unused_mut)]
        let mut $ptr: usize = 0;
    };
}

/// Port of `scan()` (PHPSRC/ext/date/lib/parse_iso_intervals.re): scans one token and applies its action.
/// Returns the token class, or `EOI` at the end of the input.
#[allow(unused_assignments, unused_variables, unused_mut, unreachable_code, clippy::all, clippy::pedantic)]
pub(crate) fn scan(s: &mut Scanner) -> i32 {
    let mut cursor = s.cur;
    let mut marker: usize = 0;

    'std: loop {
        s.tok = Some(cursor);
'''

FOOTER = r'''
    }
}

/*!max:re2c
	format = "/// `YYMAXFILL`: NUL padding appended to the input.\npub(crate) const YYMAXFILL: usize = @@;\n";
*/
'''


def main():
    upstream, out = sys.argv[1], sys.argv[2]
    with open(upstream, encoding="latin-1", newline="") as fh:
        text = fh.read()
    start = text.index("/*!re2c", text.index("std:"))
    # The block closes with a "*/" at the start of a line (the inner "/* */" ends mid-line).
    end = text.index("\n*/", start) + 3
    definitions = text[start:end]
    assert "any = [\\000-\\377];" in definitions and "combinedrep" in definitions
    rules_path = os.path.join(os.path.dirname(os.path.abspath(__file__)), "iso_scanner_rules.re.rs")
    with open(rules_path, encoding="utf-8") as fh:
        rules = fh.read()
    body = HEADER + definitions + "\n\n" + rules + FOOTER
    with open(out, "w", encoding="utf-8", newline="\n") as fh:
        fh.write(body.replace("\r\n", "\n"))
    print("definitions: %d bytes, rules: %d bytes" % (len(definitions), len(rules)))


if __name__ == "__main__":
    main()
