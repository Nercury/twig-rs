#!/usr/bin/env python3
"""Converts PHP's embedded timezone database (PHPSRC/ext/date/lib/timezonedb.h) into the form twig-timelib embeds.

Usage: python -I tools/gen_tzdb.py <PHPSRC>/ext/date/lib/timezonedb.h src/tzdb

Writes
  <out>/timezonedb.bin  the byte array PHP compiles in (the TIMELIB_SUPPORT_SLIM_FILE variant, which is the one
                        PHPSRC/ext/date/lib/parse_tz.c selects by defining TIMELIB_SUPPORT_SLIM_FILE), verbatim;
  <out>/index.rs        the index (zone identifier -> byte offset) in PHP's order, plus the database version.

Both are checked: the index must be sorted the way timelib_strcasecmp() orders it (seek_to_tz_position() binary
searches it), offsets must be increasing and inside the blob, and every entry must start with the "PHP2" magic.
"""
import re
import sys


def main():
    src, out = sys.argv[1], sys.argv[2]
    with open(src, encoding="latin-1") as fh:
        text = fh.read()

    slim_start = text.index("#ifdef TIMELIB_SUPPORT_SLIM_FILE")
    slim_end = text.index("#else", slim_start)
    slim = text[slim_start:slim_end]

    idx_m = re.search(r"timezonedb_idx_builtin\[(\d+)\] = \{(.*?)\n\};", slim, re.S)
    count = int(idx_m.group(1))
    entries = re.findall(r'\{ \(char\*\) "([^"]+)"\s*, 0x([0-9A-F]+) \}', idx_m.group(2))
    assert len(entries) == count, (len(entries), count)

    data_m = re.search(r"timelib_timezone_db_data_builtin\[(\d+)\] = \{(.*?)\n\};", slim, re.S)
    size = int(data_m.group(1))
    body = re.sub(r"/\*.*?\*/", "", data_m.group(2), flags=re.S)
    data = bytes(int(b, 16) for b in re.findall(r"0x([0-9A-F]{2})", body))
    assert len(data) == size, (len(data), size)

    ver_m = re.search(r'const timelib_tzdb timezonedb_builtin = \{ "([^"]+)", (\d+),', text)
    version, vcount = ver_m.group(1), int(ver_m.group(2))
    assert vcount == count

    def key(name):
        # timelib_strcasecmp(): ASCII tolower map, unsigned byte comparison, then length.
        return bytes(c + 32 if 65 <= c <= 90 else c for c in name.encode("ascii"))

    keys = [key(n) for n, _ in entries]
    assert all(keys[i] < keys[i + 1] for i in range(len(keys) - 1)), "index not sorted by timelib_strcasecmp"
    offsets = [int(o, 16) for _, o in entries]
    assert all(offsets[i] < offsets[i + 1] for i in range(len(offsets) - 1))
    for (name, _), off in zip(entries, offsets):
        assert data[off:off + 4] == b"PHP2", name

    with open(out + "/timezonedb.bin", "wb") as fh:
        fh.write(data)

    lines = [
        "// @generated by tools/gen_tzdb.py from PHPSRC/ext/date/lib/timezonedb.h (TIMELIB_SUPPORT_SLIM_FILE variant).",
        "// Do not edit by hand. Zone data: IANA tz database (public domain), packaged by timelib (MIT).",
        "",
        "/// Version of the embedded timezone database (`timezonedb_builtin.version`).",
        'pub(crate) const VERSION: &str = "%s";' % version,
        "",
        "/// Size in bytes of `timezonedb.bin`.",
        "pub(crate) const DATA_LEN: usize = %d;" % size,
        "",
        "/// `timezonedb_idx_builtin`: zone identifier and byte offset into the data blob, sorted for",
        "/// `timelib_strcasecmp()` binary search.",
        "pub(crate) static INDEX: [(&str, u32); %d] = [" % count,
    ]
    for name, off in entries:
        lines.append('    ("%s", 0x%06X),' % (name, int(off, 16)))
    lines.append("];")
    lines.append("")
    with open(out + "/index.rs", "w", newline="\n") as fh:
        fh.write("\n".join(lines))
    print("version %s, %d zones, %d bytes" % (version, count, size))


if __name__ == "__main__":
    main()
