#!/usr/bin/env python3
"""Converts timelib's abbreviation tables into Rust.

Usage: python -I tools/gen_abbr.py <PHPSRC>/ext/date/lib src/abbr_data.rs

Reads timezonemap.h (timelib_timezone_lookup, the `abbreviation -> offset/zone` table generated from the tz
database) and fallbackmap.h (timelib_timezone_fallbackmap, `offset/dst -> zone`), keeping order, which matters:
abbr_search() returns the first match.
"""
import re
import sys

ROW = re.compile(r'\{\s*"([^"]*)",\s*(\d+),\s*([^,]+),\s*(?:"([^"]*)"|NULL)\s*\}')


def rows(path):
    out = []
    with open(path, encoding="latin-1") as fh:
        for line in fh:
            m = ROW.search(line)
            if not m:
                continue
            name, dst, off, zone = m.group(1), int(m.group(2)), m.group(3).strip(), m.group(4)
            if not re.fullmatch(r"[-+0-9* ]+", off):
                raise SystemExit("unexpected offset expression: " + off)
            out.append((name, dst, int(eval(off)), zone))  # noqa: S307 - integer arithmetic only, checked above
    return out


def emit(name, doc, entries):
    lines = ["/// %s" % doc, "pub(crate) static %s: [TzLookup; %d] = [" % (name, len(entries))]
    for n, dst, off, zone in entries:
        tz = 'Some("%s")' % zone if zone is not None else "None"
        lines.append('    TzLookup { name: "%s", dst: %d, gmtoffset: %d, full_tz_name: %s },' % (n, dst, off, tz))
    lines.append("];")
    return lines


def main():
    lib, out = sys.argv[1], sys.argv[2]
    main_rows = rows(lib + "/timezonemap.h")
    fallback = rows(lib + "/fallbackmap.h")
    lines = [
        "// @generated by tools/gen_abbr.py from PHPSRC/ext/date/lib/timezonemap.h and fallbackmap.h. Do not edit.",
        "",
        "use super::TzLookup;",
        "",
    ]
    lines += emit("TIMEZONE_LOOKUP", "`timelib_timezone_lookup` (timezonemap.h), in upstream order.", main_rows)
    lines.append("")
    lines += emit("TIMEZONE_FALLBACKMAP", "`timelib_timezone_fallbackmap` (fallbackmap.h), in upstream order.", fallback)
    lines.append("")
    with open(out, "w", newline="\n") as fh:
        fh.write("\n".join(lines))
    print("%d abbreviations, %d fallbacks" % (len(main_rows), len(fallback)))


if __name__ == "__main__":
    main()
