#!/usr/bin/env python3
"""Assembles src/parse_date/scanner.re, the re2rust input for the strtotime() scanner.

Usage: python -I tools/gen_scanner_re.py <PHPSRC>/ext/date/lib/parse_date.re src/parse_date/scanner.re

The output is
  * a Rust prelude (imports, the TIMELIB_* action macros, the scan() function head),
  * the regular-expression definitions block of timelib's parse_date.re, copied VERBATIM (the first
    `/*!re2c ... */` block inside scan()),
  * tools/scanner_rules.re.rs: the rules block, whose patterns and order are verbatim from parse_date.re and whose
    C actions are translated to Rust one to one,
  * the function tail and `/*!max:re2c */` (YYMAXFILL).

Then run tools/regen_scanner.sh to turn scanner.re into scanner.rs with re2rust 4.1.
"""
import os
import sys

HEADER = r'''//! The `strtotime()` scanner (port of `scan()` in `PHPSRC/ext/date/lib/parse_date.re`).
//!
//! GENERATED by re2rust 4.1 from `scanner.re` (see `tools/gen_scanner_re.py` and `tools/regen_scanner.sh`); do
//! not edit by hand. The regular-expression definitions and rules are verbatim from timelib 2022.17; the actions
//! are line-by-line Rust translations of the C actions, calling the helpers in `parse_date/mod.rs`.

use super::*;
use crate::dow::daynr_from_weeknr;
use crate::types::{
    ERR_DOUBLE_DATE, ERR_DOUBLE_TIME, ERR_DOUBLE_TZ, ERR_TZID_NOT_FOUND, ERR_UNEXPECTED_CHARACTER,
    SPECIAL_DAY_OF_WEEK_IN_MONTH, SPECIAL_FIRST_DAY_OF_MONTH, SPECIAL_LAST_DAY_OF_MONTH,
    SPECIAL_LAST_DAY_OF_WEEK_IN_MONTH, SPECIAL_WEEKDAY, WARN_DOUBLE_TZ, ZONETYPE_OFFSET,
};

/// `TIMELIB_INIT`: remember where the token ends and take a NUL-terminated copy of it.
macro_rules! init {
    ($s:ident, $cursor:ident, $str:ident, $ptr:ident) => {
        $s.cur = $cursor;
        #[allow(unused_variables)]
        let $str = $s.token();
        #[allow(unused_mut, unused_variables)]
        let mut $ptr: usize = 0;
    };
}

/// `TIMELIB_HAVE_TIME()`.
macro_rules! have_time {
    ($s:ident) => {
        if $s.time.have_time != 0 {
            $s.add_error(ERR_DOUBLE_TIME, "Double time specification");
            return TIMELIB_ERROR;
        } else {
            $s.time.have_time = 1;
            $s.time.h = 0;
            $s.time.i = 0;
            $s.time.s = 0;
            $s.time.us = 0;
        }
    };
}

/// `TIMELIB_HAVE_DATE()`.
macro_rules! have_date {
    ($s:ident) => {
        if $s.time.have_date != 0 {
            $s.add_error(ERR_DOUBLE_DATE, "Double date specification");
            return TIMELIB_ERROR;
        } else {
            $s.time.have_date = 1;
        }
    };
}

/// `TIMELIB_HAVE_TZ()`: a second zone is a warning, a third one an error.
macro_rules! have_tz {
    ($s:ident, $cursor:ident) => {
        $s.cur = $cursor;
        if $s.time.have_zone != 0 {
            if $s.time.have_zone > 1 {
                $s.add_error(ERR_DOUBLE_TZ, "Double timezone specification");
            } else {
                $s.add_warning(WARN_DOUBLE_TZ, "Double timezone specification");
            }
            $s.time.have_zone += 1;
            return TIMELIB_ERROR;
        } else {
            $s.time.have_zone += 1;
        }
    };
}

/// `s->time->z = timelib_parse_zone(&ptr, &s->time->dst, s->time, &tz_not_found, s->tzdb, tz_get_wrapper);`
macro_rules! parse_zone_into {
    ($s:ident, $str:ident, $ptr:ident, $nf:ident, $w:ident) => {{
        let tzdb = $s.tzdb;
        let mut dst = $s.time.dst;
        let z = parse_zone(&$str, &mut $ptr, &mut dst, &mut $s.time, &mut $nf, tzdb, $w);
        $s.time.z = z as i32;
    }};
}

/// Port of `scan()` (PHPSRC/ext/date/lib/parse_date.re): scans one token and applies its action. Returns the
/// token class, or `EOI` at the end of the input.
#[allow(unused_assignments, unused_variables, unused_mut, unreachable_code, clippy::all, clippy::pedantic)]
pub(crate) fn scan(s: &mut Scanner<'_>, tz_get_wrapper: &mut TzGetWrapper<'_>) -> i32 {
    let mut cursor = s.cur;
    let mut marker: usize = 0;

    'std: loop {
        s.tok = Some(cursor);
'''

FOOTER = r'''
    }
}

/*!max:re2c
	format = "/// `YYMAXFILL`: NUL padding appended to the input.\npub(crate) const YYMAXFILL: usize = @@;\n";
*/
'''


def main():
    upstream, out = sys.argv[1], sys.argv[2]
    with open(upstream, encoding="latin-1", newline="") as fh:
        text = fh.read()
    start = text.index("/*!re2c", text.index("std:"))
    # The block closes with a "*/" at the start of a line (inner /* comments */ end mid-line).
    end = text.index("\n*/", start) + 3
    definitions = text[start:end]
    assert "any = [\\000-\\377];" in definitions and "weekdayof" in definitions
    rules_path = os.path.join(os.path.dirname(os.path.abspath(__file__)), "scanner_rules.re.rs")
    with open(rules_path, encoding="utf-8") as fh:
        rules = fh.read()
    # The definitions are byte-for-byte upstream (they contain UTF-8 'µs'); keep the bytes.
    body = HEADER + definitions.encode("latin-1").decode("utf-8") + "\n\n" + rules + FOOTER
    with open(out, "w", encoding="utf-8", newline="\n") as fh:
        fh.write(body.replace("\r\n", "\n"))
    print("definitions: %d bytes, rules: %d bytes" % (len(definitions), len(rules)))


if __name__ == "__main__":
    main()
